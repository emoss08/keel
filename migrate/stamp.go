package migrate

import (
	"fmt"
	"go/format"
	"go/token"
)

// Stamp returns the Go source of a file in package pkg declaring Version, the set's newest
// version, and Fingerprint, its fingerprint. A server links this file instead of its migrations
// and passes Version to Require.
func Stamp(set Set, pkg string) ([]byte, error) {
	if set.err != nil {
		return nil, set.err
	}
	if !token.IsIdentifier(pkg) {
		return nil, fmt.Errorf("migrate: stamp: %q is not a package name", pkg)
	}
	src := fmt.Sprintf(`// Code generated by keel migrate stamp. DO NOT EDIT.

package %s

const (
	// Version is the newest migration version the schema has.
	Version = %q
	// Fingerprint changes whenever any migration does.
	Fingerprint = %q
)
`, pkg, set.Version(), set.Fingerprint())
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("migrate: stamp: %w", err)
	}
	return out, nil
}
