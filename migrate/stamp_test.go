package migrate

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

func TestStamp(t *testing.T) {
	set := one(files("20260101000000_a.sql", "x", "20260102000000_b.sql", "y"))
	out, err := Stamp(set, "schema")
	if err != nil {
		t.Fatal(err)
	}
	src := string(out)
	for _, want := range []string{"// Code generated by keel migrate stamp. DO NOT EDIT.", "package schema", `Version = "20260102000000"`, `Fingerprint = "` + set.Fingerprint() + `"`} {
		if !strings.Contains(src, want) {
			t.Fatalf("missing %q in\n%s", want, src)
		}
	}
	again, _ := Stamp(one(files("20260102000000_b.sql", "y", "20260101000000_a.sql", "x")), "schema")
	if string(again) != src {
		t.Fatal("stamp is not stable")
	}
	if _, err := Stamp(set, "not a name"); err == nil {
		t.Fatal("bad package accepted")
	}
	if _, err := Stamp(one(files("bad.sql", "x")), "schema"); err == nil {
		t.Fatal("bad set accepted")
	}
}

func TestCreate(t *testing.T) {
	dir := t.TempDir()
	now := time.Date(2026, 10, 23, 14, 30, 0, 0, time.UTC)
	p1, err := Create(dir, "Add Items", CreateOptions{Now: now})
	if err != nil {
		t.Fatal(err)
	}
	p2, err := Create(dir, "add-index", CreateOptions{Now: now, NoTx: true})
	if err != nil {
		t.Fatal(err)
	}
	p3, err := Create(dir, "views", CreateOptions{Repeatable: true})
	if err != nil {
		t.Fatal(err)
	}
	if filepath.Base(p1) != "20261023143000_add_items.sql" || filepath.Base(p2) != "20261023143001_add_index.sql" || filepath.Base(p3) != "R_views.sql" {
		t.Fatalf("paths %s %s %s", p1, p2, p3)
	}
	ms, err := Sources(Source{FS: os.DirFS(dir)}).Migrations()
	if err != nil {
		t.Fatal(err)
	}
	if len(ms) != 3 || ms[0].Directives.NoTx || !ms[1].Directives.NoTx || ms[2].Kind != KindRepeatable {
		t.Fatalf("%+v", ms)
	}
	if _, err := Create(dir, "views", CreateOptions{Repeatable: true}); err == nil {
		t.Fatal("overwrote a repeatable")
	}
	if _, err := Create(dir, "bad;name", CreateOptions{}); err == nil {
		t.Fatal("bad name accepted")
	}
}
