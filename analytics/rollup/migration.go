// Migration returns the migration that creates or redefines the rollup, for keel/migrate. It runs
// outside a transaction (--keel:notx) in parts that are each safe to run again:
//
//  1. CREATE INDEX CONCURRENTLY on the source's tenant and grain columns, unless the rollup was
//     declared WithoutSourceIndex.
//  2. In one transaction: the shared keel_rollup_dirty and keel_rollup_state tables; the rollup
//     table, dropped first when an earlier definition made it, created with CREATE TABLE AS so its
//     column types are the source's, and its unique key; the trigger function and the three
//     statement triggers that mark touched slices. Holding the source's trigger lock only for this
//     DDL keeps writes waiting briefly.
//  3. Marking every existing tenant for a rebuild and recording the rollup as ready. Writes made
//     since step 2 are marked by the triggers; rows from before are covered by the tenant marks,
//     which Refresh turns into rebuilds.
//
// Row-level security and other per-table policies stay with the application: its migrate After
// statements see the rollup table like any other tenant table.
func Migration(r *Rollup) string {
	var b strings.Builder
	b.WriteString("--keel:notx\n")
	fmt.Fprintf(&b, "-- Rollup %s of %s, generated by keel's analytics/rollup. Do not edit; change the declaration and generate again.\n", r.name, r.source.Name)
	if r.sourceIndex {
		b.WriteString(r.sourceIndexSQL())
		b.WriteString("\n--keel:split\n")
	}
	b.WriteString(r.defineSQL())
	b.WriteString("\n--keel:split\n")
	b.WriteString(r.markAllSQL(true))
	b.WriteString("\n")
	return b.String()
}

// sourceIndexSQL creates the index refresh reads the source through. Its name depends only on the
// table and grain, so rollups sharing them share it.
func (r *Rollup) sourceIndexSQL() string {
	var cols []string
	for _, ci := range r.source.Tenant {
		cols = append(cols, r.source.Columns[ci].Quoted)
	}
	g := r.source.Columns[r.grain]
	cols = append(cols, schema.Quote(g.Name))
	name := truncIdent("keel_rollup_" + r.source.Name + "_" + g.Name)
	return "CREATE INDEX CONCURRENTLY IF NOT EXISTS " + schema.Quote(name) + " ON " + r.source.Quoted +
		" (" + strings.Join(cols, ", ") + ");"
}

// truncIdent shortens an identifier to Postgres's 63 bytes.
func truncIdent(s string) string {
	if len(s) > 63 {
		return s[:63]
	}
	return s
}

// funcName names the rollup's trigger function.
func (r *Rollup) funcName() string { return "keel_rollup_" + r.name }

// marker is the comment that marks a table as a rollup, so a redefinition drops only a table this
// package made.
func (r *Rollup) marker() string { return "keel rollup " + r.name + " of " + r.source.Name }

// defineSQL creates the bookkeeping tables, the rollup table and the triggers, in one transaction.
func (r *Rollup) defineSQL() string {
	name := lit(r.name)
	tbl := schema.Quote(r.name)
	sel, group := r.selectList("s")
	parts := []string{
		dirtyTableSQL,
		"DELETE FROM keel_rollup_state WHERE rollup = " + name + ";",
		"DELETE FROM keel_rollup_dirty WHERE rollup = " + name + ";",
		`DO $keel$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_class WHERE oid = to_regclass(` + lit(tbl) + `) AND obj_description(oid, 'pg_class') = ` + lit(r.marker()) + `) THEN
        DROP TABLE ` + tbl + `;
    END IF;
END
$keel$;`,
		"CREATE TABLE " + tbl + " AS SELECT " + sel + " FROM " + r.source.Quoted + " s GROUP BY " + group + " WITH NO DATA;",
		"COMMENT ON TABLE " + tbl + " IS " + lit(r.marker()) + ";",
		"CREATE UNIQUE INDEX " + schema.Quote(truncIdent(r.name+"_key")) + " ON " + tbl + " (" + r.keyColumns() + ") NULLS NOT DISTINCT;",
		r.functionSQL(),
	}
	parts = append(parts, r.triggersSQL()...)
	return strings.Join(parts, "\n")
}

// functionSQL creates the trigger function: for each statement it inserts the distinct slices the
// statement touched, from the transition tables, into keel_rollup_dirty. An update marks only the
// rows whose rollup columns changed, old and new values both, found as the multiset difference of
// the old and new rows over those columns.
func (r *Rollup) functionSQL() string {
	var cols []string
	for _, ci := range r.relevantColumns() {
		cols = append(cols, schema.Quote(r.source.Columns[ci].Name))
	}
	list := strings.Join(cols, ", ")
	mark := func(from string) string {
		return `        INSERT INTO keel_rollup_dirty (rollup, tenant_key, bucket, xid)
        SELECT DISTINCT ` + lit(r.name) + `, ` + r.tenantKeyExpr("n") + `, coalesce(` + r.bucketExpr("n") + `, 'infinity'), pg_current_xact_id()
          FROM ` + from + ` n
        ON CONFLICT DO NOTHING;`
	}
	changed := "((SELECT " + list + " FROM keel_old EXCEPT ALL SELECT " + list + " FROM keel_new) UNION ALL " +
		"(SELECT " + list + " FROM keel_new EXCEPT ALL SELECT " + list + " FROM keel_old))"
	return `CREATE OR REPLACE FUNCTION ` + r.funcName() + `() RETURNS trigger LANGUAGE plpgsql AS $keel$
BEGIN
    IF TG_OP = 'INSERT' THEN
` + mark("keel_new") + `
    ELSIF TG_OP = 'DELETE' THEN
` + mark("keel_old") + `
    ELSE
` + mark(changed) + `
    END IF;
    RETURN NULL;
END
$keel$;`
}

// triggersSQL creates the rollup's statement triggers on the source table.
func (r *Rollup) triggersSQL() []string {
	events := []struct{ event, refs string }{
		{"INSERT", "NEW TABLE AS keel_new"},
		{"UPDATE", "OLD TABLE AS keel_old NEW TABLE AS keel_new"},
		{"DELETE", "OLD TABLE AS keel_old"},
	}
	out := make([]string, len(events))
	for i, e := range events {
		name := schema.Quote(truncIdent(r.funcName() + "_" + strings.ToLower(e.event)))
		out[i] = "CREATE OR REPLACE TRIGGER " + name + " AFTER " + e.event + " ON " + r.source.Quoted +
			" REFERENCING " + e.refs + " FOR EACH STATEMENT EXECUTE FUNCTION " + r.funcName() + "();"
	}
	return out
}

// markAllSQL marks every tenant with rows in the source for a rebuild, in one statement; with
// ready it also records the rollup as ready for routing.
func (r *Rollup) markAllSQL(ready bool) string {
	mark := "INSERT INTO keel_rollup_dirty (rollup, tenant_key, bucket, xid) SELECT DISTINCT " + lit(r.name) +
		", " + r.tenantKeyExpr("s") + ", '-infinity'::timestamptz, pg_current_xact_id() FROM " + r.source.Quoted +
		" s ON CONFLICT DO NOTHING"
	if !ready {
		return mark
	}
	return "WITH marked AS (" + mark + ")\nINSERT INTO keel_rollup_state (rollup, ready_at) VALUES (" + lit(r.name) +
		", now()) ON CONFLICT (rollup) DO UPDATE SET ready_at = excluded.ready_at;"
}

// DropMigration returns the migration that removes a rollup no longer declared: its triggers on
// source, its function, its table and its bookkeeping rows.
func DropMigration(name string, source *schema.Table) (string, error) {
	if !rollupName.MatchString(name) {
		return "", fmt.Errorf("rollup: the name must match %s", rollupName)
	}
	fn := "keel_rollup_" + name
	var b strings.Builder
	for _, ev := range []string{"insert", "update", "delete"} {
		b.WriteString("DROP TRIGGER IF EXISTS " + schema.Quote(truncIdent(fn+"_"+ev)) + " ON " + source.Quoted + ";\n")
	}
	b.WriteString("DROP FUNCTION IF EXISTS " + fn + "();\n")
	b.WriteString("DROP TABLE IF EXISTS " + schema.Quote(name) + ";\n")
	b.WriteString("DELETE FROM keel_rollup_state WHERE rollup = " + lit(name) + ";\n")
	b.WriteString("DELETE FROM keel_rollup_dirty WHERE rollup = " + lit(name) + ";\n")
	return b.String(), nil
}

// Func returns the rollup's migration as a keel/migrate Go migration with the given version, for
// an application that registers rollups in code rather than as files. Its checksum covers only
// its version and name, so a changed declaration needs a new version.
func Func(version string, r *Rollup) migrate.Func {
	stmts := migrate.Migration{SQL: Migration(r), Directives: migrate.Directives{NoTx: true}}.Statements()
	return migrate.Func{
		Version: version,
		Name:    "rollup_" + r.name,
		UpNoTx: func(ctx context.Context, conn *pgx.Conn) error {
			for _, s := range stmts {
				if _, err := conn.Exec(ctx, s); err != nil {
					return fmt.Errorf("rollup: %s: %w", r.name, err)
				}
			}
			return nil
		},
	}
}

// WriteMigrations writes a migration file into dir for each rollup whose newest migration there,
// a file named <version>_rollup_<name>.sql, is missing or differs from what Migration returns now,
// and returns the paths written. Unchanged rollups get no file, so running it on every build is
// safe.
func WriteMigrations(dir string, rollups ...*Rollup) ([]string, error) {
	var written []string
	for _, r := range rollups {
		stale, err := staleMigration(dir, r)
		if err != nil {
			return written, err
		}
		if !stale {
			continue
		}
		path, err := migrate.Create(dir, "rollup_"+r.name, migrate.CreateOptions{NoTx: true})
		if err != nil {
			return written, fmt.Errorf("rollup: %w", err)
		}
		if err := os.WriteFile(path, []byte(Migration(r)), 0o644); err != nil {
			return written, fmt.Errorf("rollup: %w", err)
		}
		written = append(written, path)
	}
	return written, nil
}

// CheckMigrations returns an error naming each rollup whose newest migration in dir is missing or
// out of date, for CI.
func CheckMigrations(dir string, rollups ...*Rollup) error {
	var stale []string
	for _, r := range rollups {
		s, err := staleMigration(dir, r)
		if err != nil {
			return err
		}
		if s {
			stale = append(stale, r.name)
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("rollup: migrations of %s are missing or out of date in %s; generate them", strings.Join(stale, ", "), dir)
	}
	return nil
}

// staleMigration reports whether r's newest migration in dir is missing or differs from Migration.
func staleMigration(dir string, r *Rollup) (bool, error) {
	matches, err := filepath.Glob(filepath.Join(dir, "*_rollup_"+r.name+".sql"))
	if err != nil {
		return false, fmt.Errorf("rollup: %w", err)
	}
	var versioned []string
	for _, m := range matches {
		v, rest, _ := strings.Cut(filepath.Base(m), "_")
		if len(v) == 14 && strings.Trim(v, "0123456789") == "" && rest == "rollup_"+r.name+".sql" {
			versioned = append(versioned, m)
		}
	}
	if len(versioned) == 0 {
		return true, nil
	}
	slices.Sort(versioned)
	got, err := os.ReadFile(versioned[len(versioned)-1])
	if errors.Is(err, os.ErrNotExist) {
		return true, nil
	}
	if err != nil {
		return false, fmt.Errorf("rollup: %w", err)
	}
	return string(got) != Migration(r), nil
}
