// Package tsgen writes analytics/ir as a TypeScript module: the definition types and JSON Schema,
// the operator table per value type, the chart and transform rules, the formula function registry
// and applyFilters, so a client builder uses the server's rules instead of copies of them.
package tsgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/emoss08/keel/analytics/formula"
	"github.com/emoss08/keel/analytics/ir"
	"github.com/emoss08/keel/analytics/ir/internal/schemagen"
)

type enum struct {
	name   string
	plural string
	typ    reflect.Type
	values []string
}

func stringsOf[T ~string](values []T) []string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = string(v)
	}
	return out
}

func operands() []string {
	var out []string
	seen := map[ir.Operand]bool{}
	for _, o := range ir.Ops() {
		if !seen[o.Operand] {
			seen[o.Operand] = true
			out = append(out, string(o.Operand))
		}
	}
	return out
}

func opValues() []string {
	var out []string
	for _, o := range ir.Ops() {
		out = append(out, string(o.Op))
	}
	return out
}

func enums() []enum {
	return []enum{
		{"ValueType", "VALUE_TYPES", reflect.TypeFor[formula.Type](), stringsOf(formula.Types())},
		{"Op", "OPS", reflect.TypeFor[ir.Op](), opValues()},
		{"Operand", "OPERANDS", reflect.TypeFor[ir.Operand](), operands()},
		{"Agg", "AGGS", reflect.TypeFor[ir.Agg](), stringsOf(ir.Aggs())},
		{"Bucket", "BUCKETS", reflect.TypeFor[ir.Bucket](), stringsOf(ir.Buckets())},
		{"WindowFn", "WINDOW_FNS", reflect.TypeFor[ir.WindowFn](), stringsOf(ir.WindowFns())},
		{"TransformOp", "TRANSFORM_OPS", reflect.TypeFor[ir.TransformOp](), stringsOf(ir.TransformOps())},
		{"ChartType", "CHART_TYPES", reflect.TypeFor[ir.ChartType](), stringsOf(ir.ChartTypes())},
		{"FormulaClass", "FORMULA_CLASSES", reflect.TypeFor[formula.Class](), stringsOf(formula.Classes())},
		{"FormulaResult", "FORMULA_RESULTS", reflect.TypeFor[formula.Result](), stringsOf(formula.Results())},
	}
}

type emitter struct {
	b       bytes.Buffer
	enums   []enum
	byValue map[string]string
	byType  map[reflect.Type]string
}

// Options configure Generate.
type Options struct {
	// Schema is the JSON Schema to embed and derive the definition types from; nil uses ir.Schema.
	Schema []byte
}

// Generate returns the TypeScript module.
func Generate(opts Options) ([]byte, error) {
	if opts.Schema == nil {
		opts.Schema = ir.Schema()
	}
	e := &emitter{enums: enums(), byValue: map[string]string{}, byType: map[reflect.Type]string{}}
	for _, en := range e.enums {
		e.byValue[strings.Join(en.values, "\x00")] = en.name
		e.byType[en.typ] = en.name
	}
	e.line("// Code generated by keel analytics/ir/tsgen. DO NOT EDIT.")
	e.line("")
	e.line("export const DEFINITION_VERSION = %d;", ir.Version)
	e.enumTypes()
	if err := e.definitionTypes(opts.Schema); err != nil {
		return nil, err
	}
	if err := e.data(opts.Schema); err != nil {
		return nil, err
	}
	e.b.WriteString(applyFiltersTS)
	return e.b.Bytes(), nil
}

// Write writes the module to path, creating its directory.
func Write(path string) error {
	out, err := Generate(Options{})
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, out, 0o644)
}

// Check reports an error when the file at path differs from what Generate writes.
func Check(path string) error {
	want, err := Generate(Options{})
	if err != nil {
		return err
	}
	got, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s is out of date; regenerate it", path)
	}
	return nil
}

func (e *emitter) line(format string, args ...any) {
	fmt.Fprintf(&e.b, format, args...)
	e.b.WriteString("\n")
}

func literal(s string) string {
	out, _ := schemagen.Marshal(s)
	return strings.TrimSuffix(string(out), "\n")
}

func union(values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = literal(v)
	}
	return strings.Join(parts, " | ")
}

func (e *emitter) enumTypes() {
	for _, en := range e.enums {
		e.line("")
		e.line("export type %s = %s;", en.name, union(en.values))
		e.line("export const %s: readonly %s[] = [%s];", en.plural, en.name, strings.Join(quoted(en.values), ", "))
	}
}

func quoted(values []string) []string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = literal(v)
	}
	return out
}

func (e *emitter) definitionTypes(raw []byte) error {
	var schema struct {
		Defs map[string]map[string]any `json:"$defs"`
	}
	if err := json.Unmarshal(raw, &schema); err != nil {
		return err
	}
	names := make([]string, 0, len(schema.Defs))
	for n := range schema.Defs {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		def := schema.Defs[n]
		e.line("")
		e.doc(def, "")
		e.line("export type %s = %s;", n, e.tsOf(def, ""))
	}
	return nil
}

func (e *emitter) doc(s map[string]any, indent string) { e.b.WriteString(docLine(s, indent)) }

func docLine(s map[string]any, indent string) string {
	if d, ok := s["description"].(string); ok && d != "" {
		return indent + "/** " + strings.ReplaceAll(d, "*/", "* /") + " */\n"
	}
	return ""
}

func (e *emitter) tsOf(s map[string]any, indent string) string {
	if ref, ok := s["$ref"].(string); ok {
		return strings.TrimPrefix(ref, "#/$defs/")
	}
	if c, ok := s["const"]; ok {
		out, _ := schemagen.Marshal(c)
		return strings.TrimSuffix(string(out), "\n")
	}
	if values, ok := s["enum"].([]any); ok {
		strs := make([]string, len(values))
		for i, v := range values {
			strs[i] = v.(string)
		}
		if name, ok := e.byValue[strings.Join(strs, "\x00")]; ok {
			return name
		}
		return union(strs)
	}
	if variants, ok := s["oneOf"].([]any); ok && s["properties"] == nil {
		parts := make([]string, len(variants))
		for i, v := range variants {
			parts[i] = e.tsOf(v.(map[string]any), indent)
		}
		return strings.Join(parts, " | ")
	}
	switch s["type"] {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		item := e.tsOf(s["items"].(map[string]any), indent)
		if strings.Contains(item, " | ") {
			item = "(" + item + ")"
		}
		return item + "[]"
	case "object":
		return e.objectOf(s, indent)
	default:
		return "unknown"
	}
}

func (e *emitter) objectOf(s map[string]any, indent string) string {
	props, _ := s["properties"].(map[string]any)
	if len(props) == 0 {
		return "Record<string, unknown>"
	}
	required := map[string]bool{}
	if req, ok := s["required"].([]any); ok {
		for _, r := range req {
			required[r.(string)] = true
		}
	}
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("{\n")
	for _, k := range keys {
		p := props[k].(map[string]any)
		b.WriteString(docLine(p, indent+"  "))
		mark := "?"
		if required[k] {
			mark = ""
		}
		fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, k, mark, e.tsOf(p, indent+"  "))
	}
	b.WriteString(indent + "}")
	return b.String()
}
